function updateSitemap(tools) {
  const path = join(ROOT, 'public/sitemap.xml');
  let xml = readFileSync(path, 'utf8');
  for (const t of tools) {
    const block = `  <url>
    <loc>https://html2design.com/use-cases/${t.slug}</loc>
    <lastmod>${TODAY}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
    <image:image>
      <image:loc>https://html2design.com/og/use-cases/${t.slug}.svg</image:loc>
      <image:title>${t.listName}</image:title>
      <image:caption>${t.sitemapCaption}</image:caption>
    </image:image>
  </url>
`;
    const existingBlocks = new RegExp(
      `^[ \\t]*<url>(?:(?!</url>)[\\s\\S])*?<loc>https://html2design\\.com/use-cases/${t.slug}</loc>(?:(?!</url>)[\\s\\S])*?</url>\\n?`,
      'gm'
    );
    xml = xml.replace(existingBlocks, '');
    xml = xml.replace('</urlset>', `${block}</urlset>`);
  }
  writeFileSync(path, xml);
}

function updateHub(tools) {
  const path = join(ROOT, 'public/use-cases/index.html');
  let html = readFileSync(path, 'utf8');

  // ItemList JSON-LD: bump numberOfItems and append entries.
  const listMatch = html.match(/"numberOfItems":\s*(\d+)/);
  if (listMatch) {
    let n = parseInt(listMatch[1], 10);
    for (const t of tools) {
      const sentinel = `"url": "https://html2design.com/use-cases/${t.slug}"`;
      if (html.includes(sentinel)) continue;
      n += 1;
      const entry = `      { "@type": "ListItem", "position": ${n}, "name": "${t.listName}",          "url": "https://html2design.com/use-cases/${t.slug}" }`;
      html = html.replace(
        /(\{ "@type": "ListItem", "position": \d+, "name": "[^"]+",[^}]+url": "[^"]+" \})\n    \]/,
        (m, last) => `${last},\n${entry}\n    ]`
      );
    }
    html = html.replace(/"numberOfItems":\s*\d+/, `"numberOfItems": ${n}`);
  }

  // AI Design Tools category — insert cards before that section's closing </div></section>.
  // We append before the closing `      </div>\n    </section>` of the ai-tools section.
  const aiSectionRe =
    /(<section class="mb-14" id="ai-tools">[\s\S]*?)(\n      <\/div>\n    <\/section>)/;
  for (const t of tools) {
    const card = `\n        <a href="/use-cases/${t.slug}" class="group block bg-white border border-gray-100 rounded-2xl p-5 hover:border-accent/30 hover:shadow-md transition-all duration-200">
          <p class="text-[10px] font-mono uppercase tracking-widest text-accent mb-2">${t.category}</p>
          <h3 class="text-base font-bold tracking-tight text-content mb-1.5 group-hover:text-accent transition-colors">${t.cardTitle}</h3>
          <p class="text-xs text-content-muted leading-relaxed">${t.cardDesc}</p>
        </a>\n`;
    const existingCard = new RegExp(
      `\\n[ \\t]*<a href="/use-cases/${t.slug}" class="group block bg-white[\\s\\S]*?</a>[ \\t]*\\n?`
    );
    html = existingCard.test(html)
      ? html.replace(existingCard, card)
      : html.replace(aiSectionRe, `$1${card}$2`);
  }

  writeFileSync(path, html);
}

function updateLlms(tools) {
  const path = join(ROOT, 'public/llms.txt');
  let txt = readFileSync(path, 'utf8');

  // Update "(N total)" + add bullets.
  const headerRe = /## Use case pages \((\d+) total\)/;
  const headerMatch = txt.match(headerRe);
  if (!headerMatch) return;
  let n = parseInt(headerMatch[1], 10);
  const toAdd = [];
  for (const t of tools) {
    const url = `https://html2design.com/use-cases/${t.slug}`;
    if (txt.includes(url)) continue;
    toAdd.push(`- ${t.listName} — ${url}`);
    n += 1;
  }
  if (toAdd.length === 0) return;
  txt = txt.replace(headerRe, `## Use case pages (${n} total)`);
  // Insert after the existing v0 line for grouping with other AI-tool entries.
  txt = txt.replace(
    /(- v0 to Figma — https:\/\/html2design\.com\/use-cases\/v0-to-figma\n)/,
    `$1${toAdd.join('\n')}\n`
  );
  writeFileSync(path, txt);
}

